"""Guided ARCA certificate flow: request (CSR + private key) and installation
of the certificate ARCA returns.

ARCA signs certificates for a CSR generated by the taxpayer. The private key
never leaves Odoo: it is created here together with the CSR, kept in
``certificate.key`` and paired again with the ``.crt`` file once ARCA answers,
which can be days later. That is why the request is a persistent record and not
a wizard.
"""

import re

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.x509.oid import NameOID

from odoo import _, api, fields, models
from odoo.exceptions import UserError, ValidationError
from odoo.tools import BinaryBytes

ALIAS_RE = re.compile(r'^[A-Za-z0-9]{1,30}$')
CUIT_WEIGHTS = (5, 4, 3, 2, 7, 6, 5, 4, 3, 2)


def _cuit_digits(value):
    return ''.join(char for char in (value or '') if char.isdigit())


def _valid_cuit(digits):
    if len(digits) != 11 or not digits.isdigit():
        return False
    remainder = 11 - sum(int(digits[i]) * CUIT_WEIGHTS[i] for i in range(10)) % 11
    check = 0 if remainder == 11 else (9 if remainder == 10 else remainder)
    return check == int(digits[10])


def _certificate_cuit(cert):
    """CUIT in the certificate subject (``serialNumber=CUIT 30712345671``)."""
    for attribute in cert.subject.get_attributes_for_oid(NameOID.SERIAL_NUMBER):
        digits = _cuit_digits(attribute.value)
        if len(digits) == 11:
            return digits
    return ''


def _certificate_environment(cert):
    """ARCA signs homologation certificates with "Computadores Test"."""
    issuer = ' '.join(attribute.value for attribute in cert.issuer.get_attributes_for_oid(NameOID.COMMON_NAME))
    issuer = issuer.lower()
    if 'computadores' not in issuer:
        return False
    return 'testing' if 'test' in issuer else 'production'


def _public_key_pem(public_key):
    return public_key.public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )


ENVIRONMENTS = [
    ('testing', 'Homologación (pruebas)'),
    ('production', 'Producción'),
]


class L10nArArcaCertificateRequest(models.Model):
    _name = 'l10n_ar.arca.certificate.request'
    _description = 'Pedido de certificado ARCA'
    _order = 'create_date desc, id desc'

    name = fields.Char(string='Pedido', compute='_compute_name', store=True)
    company_id = fields.Many2one(
        'res.company',
        string='Empresa',
        required=True,
        default=lambda self: self.env.company,
        ondelete='cascade',
    )
    cuit = fields.Char(string='CUIT', compute='_compute_cuit')
    alias = fields.Char(
        string='Alias del certificado',
        required=True,
        default='odoo',
        help='Nombre corto, sin espacios ni símbolos, que vas a ver en ARCA como "computador fiscal". '
             'Usá uno distinto por instalación, por ejemplo "odoo" o "odoolocal".',
    )
    environment = fields.Selection(
        ENVIRONMENTS,
        string='Ambiente',
        required=True,
        default=lambda self: self.env.company.l10n_ar_afip_ws_environment or 'production',
        help='Producción: el certificado se pide en "Administración de Certificados Digitales". '
             'Homologación: se pide en "WSASS - Autogestión Certificados Homologación".',
    )
    state = fields.Selection(
        [
            ('draft', 'Borrador'),
            ('waiting', 'Esperando el certificado de ARCA'),
            ('done', 'Certificado instalado'),
            ('cancel', 'Cancelado'),
        ],
        string='Estado',
        default='draft',
        required=True,
        readonly=True,
        copy=False,
    )
    key_id = fields.Many2one('certificate.key', string='Clave privada', readonly=True, copy=False)
    csr_file = fields.Binary(string='Pedido (CSR)', readonly=True, attachment=True, copy=False)
    csr_filename = fields.Char(readonly=True, copy=False)
    csr_text = fields.Text(string='Contenido del pedido', compute='_compute_csr_text')
    certificate_id = fields.Many2one('certificate.certificate', string='Certificado', readonly=True, copy=False)
    certificate_date_end = fields.Datetime(related='certificate_id.date_end', string='Vence')
    requested_date = fields.Datetime(string='Generado el', readonly=True, copy=False)

    @api.depends('alias', 'company_id', 'environment')
    def _compute_name(self):
        labels = {'testing': _('homologación'), 'production': _('producción')}
        for request in self:
            request.name = '%s - %s (%s)' % (
                request.company_id.name or '', request.alias or '', labels.get(request.environment, ''))

    @api.depends('company_id.vat')
    def _compute_cuit(self):
        for request in self:
            request.cuit = _cuit_digits(request.company_id.vat)

    @api.depends('csr_file')
    def _compute_csr_text(self):
        for request in self:
            content = request.csr_file.content if request.csr_file else b''
            request.csr_text = content.decode('ascii', errors='ignore') if content else False

    @api.constrains('alias')
    def _check_alias(self):
        for request in self:
            if not ALIAS_RE.match(request.alias or ''):
                raise ValidationError(_(
                    'El alias solo puede tener letras y números, sin espacios (hasta 30). Ejemplo: "odoo".'))

    # ------------------------------------------------------------------
    # Step 1: CSR
    # ------------------------------------------------------------------
    def action_generate_csr(self):
        """Create the private key and the CSR ARCA asks for.

        A new key is created for every request, so the certificate ARCA returns
        always matches the key kept with it.
        """
        for request in self:
            if request.state != 'draft':
                raise UserError(_('Este pedido ya fue generado. Creá un pedido nuevo si necesitás otro certificado.'))
            cuit = request.cuit
            if not _valid_cuit(cuit):
                raise UserError(_(
                    'La empresa "%s" no tiene un CUIT válido. Cargalo en la empresa antes de pedir el certificado.'
                ) % request.company_id.name)
            key = self.env['certificate.key'].sudo()._generate_rsa_private_key(
                request.company_id,
                name='ARCA %s %s.key' % (request.alias, cuit),
            )
            private_key = serialization.load_pem_private_key(key.pem_key.content, password=None)
            subject = x509.Name([
                x509.NameAttribute(NameOID.COUNTRY_NAME, 'AR'),
                x509.NameAttribute(NameOID.ORGANIZATION_NAME, (request.company_id.name or cuit)[:64]),
                x509.NameAttribute(NameOID.COMMON_NAME, request.alias),
                x509.NameAttribute(NameOID.SERIAL_NUMBER, 'CUIT %s' % cuit),
            ])
            csr = x509.CertificateSigningRequestBuilder().subject_name(subject).sign(private_key, hashes.SHA256())
            request.write({
                'key_id': key.id,
                'csr_file': BinaryBytes(csr.public_bytes(serialization.Encoding.PEM)),
                'csr_filename': '%s_%s.csr' % (request.alias, cuit),
                'state': 'waiting',
                'requested_date': fields.Datetime.now(),
            })
        return True

    def action_download_csr(self):
        self.ensure_one()
        if not self.csr_file:
            raise UserError(_('Primero generá el pedido.'))
        return {
            'type': 'ir.actions.act_url',
            'url': '/web/content/%s/%s/csr_file/%s?download=true' % (self._name, self.id, self.csr_filename),
            'target': 'download',
        }

    def action_cancel(self):
        self.filtered(lambda request: request.state in ('draft', 'waiting')).write({'state': 'cancel'})
        return True

    # ------------------------------------------------------------------
    # Step 2: certificate returned by ARCA
    # ------------------------------------------------------------------
    def action_open_upload(self):
        self.ensure_one()
        return {
            'type': 'ir.actions.act_window',
            'name': _('Cargar certificado de ARCA'),
            'res_model': 'l10n_ar.arca.certificate.upload',
            'view_mode': 'form',
            'target': 'new',
            'context': {
                'default_company_id': self.company_id.id,
                'default_request_id': self.id,
            },
        }

    @api.model
    def _l10n_ar_install_certificate(self, company, content, filename=False, request=False,
                                     key_content=False, password=False, set_as_company=True,
                                     use_for_padron=False):
        """Validate an ARCA certificate file, pair it with its private key and install it.

        :return: the ``certificate.certificate`` record
        """
        Certificate = self.env['certificate.certificate'].sudo()
        Key = self.env['certificate.key'].sudo()
        password_bytes = password.encode('utf-8') if password else None
        leaf_pem, _chain, content_format = Certificate._parse_certificate_content(content, password_bytes)
        if not leaf_pem:
            raise UserError(_(
                'El archivo "%s" no es un certificado que Odoo pueda leer. Subí el archivo .crt (o .pem) que '
                'descargaste de ARCA; si es un .p12/.pfx, completá su contraseña.'
            ) % (filename or _('sin nombre')))
        cert = x509.load_pem_x509_certificate(leaf_pem)
        cert_public = _public_key_pem(cert.public_key())

        # The certificate must be for this company's CUIT.
        company_cuit = _cuit_digits(company.vat)
        cert_cuit = _certificate_cuit(cert)
        if cert_cuit and company_cuit and cert_cuit != company_cuit:
            raise UserError(_(
                'El certificado es del CUIT %(cert)s y la empresa "%(company)s" tiene CUIT %(company_cuit)s. '
                'Cambiá de empresa arriba a la derecha o subí el certificado correcto.',
                cert=cert_cuit, company=company.name, company_cuit=company_cuit,
            ))
        now = fields.Datetime.now()
        not_after = cert.not_valid_after_utc.replace(tzinfo=None)
        if not_after < now:
            raise UserError(_('El certificado venció el %s. Pedí uno nuevo en ARCA.') % not_after)

        # Find the private key that matches the certificate.
        key = Key
        embedded_key = None
        if content_format in ('pkcs12', 'pem'):
            try:
                if content_format == 'pkcs12':
                    from cryptography.hazmat.primitives.serialization import pkcs12
                    embedded_key = pkcs12.load_key_and_certificates(content, password_bytes)[0]
                else:
                    embedded_key = serialization.load_pem_private_key(content, password=password_bytes)
            except (TypeError, ValueError):
                embedded_key = None
        if embedded_key is not None:
            if _public_key_pem(embedded_key.public_key()) != cert_public:
                raise UserError(_('La clave incluida en el archivo no corresponde al certificado.'))
            key = Key.create({
                'name': '%s.key' % (filename or 'ARCA'),
                'content': BinaryBytes(embedded_key.private_bytes(
                    encoding=serialization.Encoding.PEM,
                    format=serialization.PrivateFormat.PKCS8,
                    encryption_algorithm=serialization.NoEncryption(),
                )),
                'company_id': company.id,
            })
        elif key_content:
            key = Key.create({
                'name': 'ARCA %s.key' % (company_cuit or company.name),
                'content': BinaryBytes(key_content),
                'password': password or False,
                'company_id': company.id,
            })
            if key.loading_error or key.public:
                raise UserError(_(
                    'No se pudo leer la clave privada. Revisá que sea el archivo .key correcto y su contraseña.'))
            if key._get_public_key_bytes(encoding='pem', formatting='') != cert_public:
                raise UserError(_('La clave privada subida no corresponde a este certificado.'))
        else:
            candidates = Key
            if request and request.key_id:
                candidates |= request.key_id.sudo()
            candidates |= self.sudo().search([
                ('company_id', '=', company.id), ('state', '=', 'waiting'), ('key_id', '!=', False),
            ]).key_id
            candidates |= Key.search([('company_id', '=', company.id), ('public', '=', False)])
            for candidate in candidates:
                if candidate.loading_error or candidate.public:
                    continue
                try:
                    if candidate._get_public_key_bytes(encoding='pem', formatting='') == cert_public:
                        key = candidate
                        break
                except (TypeError, ValueError):
                    continue
            if not key:
                if request and request.key_id:
                    raise UserError(_(
                        'Este certificado no corresponde al pedido "%s". Seguramente es de otro pedido o de otra '
                        'instalación: subilo desde "Cargar certificado" en Ajustes > ARCA, o adjuntá también su '
                        'archivo .key.'
                    ) % request.name)
                raise UserError(_(
                    'No encontré en Odoo la clave privada de este certificado. Si el pedido (CSR) se generó fuera '
                    'de Odoo, subí también el archivo .key que se creó junto con él.'))

        if not request:
            request = self.sudo().search([
                ('company_id', '=', company.id), ('key_id', '=', key.id), ('state', 'in', ('draft', 'waiting')),
            ], limit=1)
        environment = _certificate_environment(cert) or (request and request.environment) or \
            company.l10n_ar_afip_ws_environment or 'production'

        existing = Certificate.search([
            ('company_id', '=', company.id),
            ('serial_number', '=', str(cert.serial_number)),
            ('private_key_id', '=', key.id),
        ], limit=1)
        if existing:
            certificate = existing
        else:
            common_name = Certificate._get_common_name(cert) or 'ARCA'
            certificate = Certificate.create({
                'name': 'ARCA %s %s (%s)' % (
                    common_name, cert_cuit or company_cuit, dict(ENVIRONMENTS)[environment]),
                'content': BinaryBytes(content),
                'pkcs12_password': password if content_format == 'pkcs12' else False,
                'private_key_id': key.id,
                'company_id': company.id,
            })
            if certificate.private_key_id != key:
                certificate.private_key_id = key

        connections = self.env['l10n_ar.afipws.connection'].sudo()
        if set_as_company:
            company.sudo().write({
                'l10n_ar_afip_ws_crt_id': certificate.id,
                'l10n_ar_afip_ws_key_id': key.id,
                'l10n_ar_afip_ws_environment': environment,
            })
            # Tickets signed with the previous certificate belong to another
            # identity: drop them so the next call signs with the new one.
            connections.search([('company_id', '=', company.id)]).write({
                'token': False, 'sign': False, 'expiration_time': now,
            })
        if use_for_padron:
            params = self.env['ir.config_parameter'].sudo()
            params.set_str('dolan_l10n_ar_afip.padron_certificate_id', str(certificate.id))
            params.set_str('dolan_l10n_ar_afip.padron_key_id', str(key.id))
            params.set_str('dolan_l10n_ar_afip.padron_representative_company_id', str(company.id))
            connections.search([('l10n_ar_afip_ws', '=', 'ws_sr_constancia_inscripcion')]).write({
                'token': False, 'sign': False, 'expiration_time': now,
            })
        if request:
            request.sudo().write({
                'state': 'done',
                'certificate_id': certificate.id,
                'key_id': key.id,
                'environment': environment,
            })
        return certificate


class L10nArArcaCertificateUpload(models.TransientModel):
    _name = 'l10n_ar.arca.certificate.upload'
    _description = 'Cargar certificado devuelto por ARCA'

    company_id = fields.Many2one(
        'res.company', string='Empresa', required=True, default=lambda self: self.env.company)
    request_id = fields.Many2one(
        'l10n_ar.arca.certificate.request',
        string='Pedido',
        domain="[('company_id', '=', company_id), ('state', '=', 'waiting')]",
        help='Opcional: si no lo elegís, Odoo busca solo la clave que corresponde al certificado.',
    )
    certificate_file = fields.Binary(string='Certificado de ARCA (.crt)')
    certificate_filename = fields.Char()
    certificate_text = fields.Text(
        string='O pegá el certificado',
        help='En homologación (WSASS) ARCA muestra el certificado como texto: copialo completo, '
             'desde -----BEGIN CERTIFICATE----- hasta -----END CERTIFICATE-----.',
    )
    key_file = fields.Binary(
        string='Clave privada (.key)',
        help='Solo si el pedido se generó fuera de Odoo (por ejemplo con OpenSSL).',
    )
    key_filename = fields.Char()
    password = fields.Char(string='Contraseña', help='Contraseña del .p12/.pfx o de la clave, si tiene.')
    set_as_company = fields.Boolean(string='Usarlo para facturar con esta empresa', default=True)
    use_for_padron = fields.Boolean(
        string='Usarlo también para consultar el padrón desde todas las empresas',
        help='Las consultas de CUIT de clientes nuevos se hacen con este certificado en todas las empresas. '
             'Requiere autorizar el servicio ws_sr_constancia_inscripcion en ARCA.',
    )
    show_key_upload = fields.Boolean(string='El pedido se generó fuera de Odoo')

    def action_confirm(self):
        self.ensure_one()
        if self.certificate_file:
            content = self.certificate_file.content
        elif (self.certificate_text or '').strip():
            content = self.certificate_text.strip().encode('utf-8')
        else:
            raise UserError(_('Subí el archivo del certificado o pegá su contenido.'))
        certificate = self.env['l10n_ar.arca.certificate.request']._l10n_ar_install_certificate(
            self.company_id,
            content,
            filename=self.certificate_filename or _('certificado pegado'),
            request=self.request_id,
            key_content=self.key_file.content if self.key_file else False,
            password=self.password,
            set_as_company=self.set_as_company,
            use_for_padron=self.use_for_padron,
        )
        message = _('Certificado "%(name)s" instalado para %(company)s. Vence el %(date)s.',
                    name=certificate.name, company=self.company_id.name,
                    date=fields.Date.to_string(certificate.date_end.date()) if certificate.date_end else '-')
        return {
            'type': 'ir.actions.client',
            'tag': 'display_notification',
            'params': {
                'title': _('Certificado ARCA cargado'),
                'message': message + ' ' + _('Probá la conexión con los botones de Ajustes > ARCA.'),
                'type': 'success',
                'sticky': False,
                'next': {'type': 'ir.actions.client', 'tag': 'soft_reload'},
            },
        }
